"""Generate db/005_seed_permissions.sql from app/permissions/seed/.

    python scripts/build_seed_sql.py          # rewrite the SQL file
    python scripts/build_seed_sql.py --check  # exit 1 if it is out of date

The JSON is the source of truth: tests build their snapshot from it and
tests/test_permissions_equivalence.py proves it reproduces app/capabilities.py.
tests/test_seed_sql.py fails if the committed SQL no longer matches it.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.permissions.catalogue import (  # noqa: E402
    catalogue_from_manifest,
    expand_grants,
    load_grants,
    load_manifests,
    load_roles,
)

TARGET = ROOT / 'db' / '005_seed_permissions.sql'

HEADER = """\
-- GENERATED by scripts/build_seed_sql.py from app/permissions/seed/. Do not edit
-- by hand: change the JSON and rerun the script.
--
-- The initial roles, catalogue and grants. Together they reproduce exactly what
-- app/capabilities.py granted (tests/test_permissions_equivalence.py) and what
-- each service enforced in its own code (docs/ARCHITECTURE_ADMIN.md).
--
-- Apply after 004_permissions.sql. Safe to re-run: roles and services are only
-- inserted when missing, a service's catalogue only when it has never pushed a
-- manifest, and its grants only while nobody has edited them (grants_version 0).
-- So re-running never undoes what admins or deploys have changed since.
"""


def _sql_text(value: str | None) -> str:
    if value is None:
        return 'null'
    return "'" + value.replace("'", "''") + "'"


def _json_literal(value: object) -> str:
    text = json.dumps(value, indent=2, ensure_ascii=False)
    assert '$json$' not in text
    return f'$json${text}$json$::jsonb'


def build() -> str:
    manifests = load_manifests()
    grants = load_grants()
    parts = [HEADER]

    parts.append('-- ── Roles ' + '─' * 70 + '\n')
    rows = ',\n'.join(
        '    ({key}, {label}, {description}, {priority}, {superuser}, {group})'.format(
            key=_sql_text(r['key']), label=_sql_text(r['label']),
            description=_sql_text(r.get('description', '')), priority=int(r['priority']),
            superuser='true' if r.get('is_superuser') else 'false',
            group=_sql_text(r.get('exclusive_group')),
        )
        for r in load_roles()
    )
    parts.append(
        'insert into public.identity_roles\n'
        '    (key, label, description, priority, is_superuser, exclusive_group)\n'
        f'values\n{rows}\non conflict (key) do nothing;\n'
    )

    parts.append('\n-- ── Services ' + '─' * 67 + '\n')
    rows = ',\n'.join(
        '    ({key}, {name}, {description}, {system})'.format(
            key=_sql_text(m['service']), name=_sql_text(m.get('name', m['service'])),
            description=_sql_text(m.get('description', '')),
            system='true' if m.get('is_system') else 'false',
        )
        for m in manifests.values()
    )
    parts.append(
        'insert into public.identity_services (key, name, description, is_system)\n'
        f'values\n{rows}\non conflict (key) do nothing;\n'
    )

    parts.append('\n-- ── Catalogues: only for a service that has never pushed its own manifest ──\n')
    for key, manifest in manifests.items():
        body = {k: v for k, v in manifest.items() if k in ('resources', 'attributes')}
        parts.append(
            f'\nselect public.identity_apply_manifest({_sql_text(key)}, {_json_literal(body)}, null, false)\n'
            f' where (select s.manifest_pushed_at from public.identity_services s\n'
            f'         where s.key = {_sql_text(key)}) is null;\n'
        )

    parts.append('\n-- ── Grants: only while nobody has edited them ─────────────────────────────\n')
    for key, manifest in manifests.items():
        expanded = expand_grants(grants.get(key, {}), catalogue_from_manifest(manifest))
        system = 'true' if manifest.get('is_system') else 'false'
        parts.append(
            f'\nselect public.identity_set_service_grants(\n'
            f'    {_sql_text(key)}, {_json_literal(expanded)}, 0, null, {system})\n'
            f' where (select s.grants_version from public.identity_services s\n'
            f'         where s.key = {_sql_text(key)}) = 0;\n'
        )

    parts.append("""
-- ── Existing role assignments ────────────────────────────────────────────────
-- user_profiles.roles was the source of truth before 004; it is a mirror now.
insert into public.identity_user_roles (user_id, role_id)
select p.user_id, r.id
  from public.user_profiles p
  cross join lateral unnest(p.roles) as held(key)
  join public.identity_roles r on r.key = held.key
on conflict do nothing;

-- ── Broker Tools desk, from team_members.role ────────────────────────────────
-- Broker Tools' auto-assignment, distribution pool, handover and team reports
-- selected people by team_members.role. They read broker_tools.desk from
-- identity_user_attribute_values instead, so it starts with the same values.
-- Skipped where team_members does not exist (a fresh project).
do $$
begin
    if to_regclass('public.team_members') is not null then
        insert into public.identity_user_attributes (user_id, attribute_id, value)
        select distinct on (tm.supabase_user_id) tm.supabase_user_id, a.id, tm.role
          from public.team_members tm
          join public.user_profiles p on p.user_id = tm.supabase_user_id
          join public.identity_services s on s.key = 'broker_tools'
          join public.identity_attributes a on a.service_id = s.id and a.key = 'desk'
         where tm.role in ('presales', 'sales')
         order by tm.supabase_user_id, tm.id
        on conflict do nothing;
    end if;
end;
$$;
""")
    return ''.join(parts)


def main() -> int:
    sql = build()
    if '--check' in sys.argv:
        current = TARGET.read_text(encoding='utf-8') if TARGET.exists() else ''
        if current != sql:
            print(f'{TARGET.relative_to(ROOT)} is out of date; run python scripts/build_seed_sql.py')
            return 1
        return 0
    TARGET.write_text(sql, encoding='utf-8', newline='\n')
    print(f'wrote {TARGET.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
