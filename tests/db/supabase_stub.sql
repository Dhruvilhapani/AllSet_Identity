-- Just enough of a Supabase project for db/001-005 to apply: the four roles
-- they grant to or revoke from, and the auth tables they reference.
do $$
begin
    if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
    if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
    if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
    if not exists (select 1 from pg_roles where rolname = 'supabase_auth_admin') then create role supabase_auth_admin nologin; end if;
end;
$$;

-- Supabase grants the API roles everything in public by default.
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on functions to anon, authenticated, service_role;
grant usage on schema public to anon, authenticated, service_role;

create schema if not exists auth;
create table if not exists auth.users (id uuid primary key, email text);
create table if not exists auth.refresh_tokens (id bigserial primary key, user_id varchar(255));
create table if not exists auth.sessions (id uuid primary key default gen_random_uuid(), user_id uuid);

-- Broker Tools' table, for the desk backfill in 005.
create table if not exists public.team_members (
    id bigint generated by default as identity primary key,
    name text not null, role text not null, phone text not null, email text not null,
    supabase_user_id uuid
);
